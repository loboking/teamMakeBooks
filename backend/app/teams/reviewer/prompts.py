def _extract_narrative(draft: str) -> str:
    """대사·시스템 메시지·헤더 제외한 서술 텍스트 추출."""
    text = draft
    text = re.sub(r'"[^"]*"', '', text)        # 곧은 따옴표 대사 제거
    text = re.sub(r'“[^”]*”', '', text)  # 곱따옴표 대사 제거
    text = re.sub(r'\[.*?\]', '', text)         # 시스템 메시지 제거
    lines = text.split('\n')
    narrative = []
    for line in lines:
        s = line.strip()
        if not s or s.startswith('#') or s.startswith('>') or s.startswith('---'):
            continue
        narrative.append(s)
    return '\n'.join(narrative)


_ACTION_VERBS = [
    '바라보았다', '확인했다', '끄덕였다', '미세하게', '입을 열었다',
    '발동했다', '눈을 감았다', '손을 뻗었다', '분석했다', '눈을 떴다',
    '주먹을 쥐었다', '깊이 숨을', '고개를 돌렸다',
]

_GRADE_KEYWORDS = ['F급', 'D급', 'C급', 'B급', 'A급', 'S급']


def _count_repetition_patterns(draft: str) -> dict:
    """서술 텍스트에서 반복 패턴 regex 카운트."""
    narrative = _extract_narrative(draft)
    counts: dict = {}

    counts['이준'] = len(re.findall(r'이준', narrative))
    counts['강이준'] = len(re.findall(r'강이준', narrative))

    verbs = {}
    for verb in _ACTION_VERBS:
        c = len(re.findall(re.escape(verb), narrative))
        if c > 0:
            verbs[verb] = c
    counts['동작동사'] = verbs

    # 연속 주어 패턴
    max_consec = 0
    cur = 0
    for line in narrative.split('\n'):
        if re.match(r'(이준|그|강이준)[은는이가을를의]', line.lstrip()):
            cur += 1
            if cur > max_consec:
                max_consec = cur
        else:
            cur = 0
    counts['연속주어'] = max_consec

    grades = {}
    for kw in _GRADE_KEYWORDS:
        c = len(re.findall(re.escape(kw), narrative))
        if c > 0:
            grades[kw] = c
    counts['등급직업'] = grades

    return counts


def _format_count_report(counts: dict) -> str:
    """카운트 결과를 프롬프트용으로 포맷."""
    lines = []
    ij = counts['이준']
    lines.append(f"서술 '이준': {ij}회 (한계 15) {'⚠️ 초과' if ij > 15 else '✓'}")
    kj = counts['강이준']
    lines.append(f"서술 '강이준': {kj}회 (한계 7) {'⚠️ 초과' if kj > 7 else '✓'}")
    for verb, c in sorted(counts.get('동작동사', {}).items(), key=lambda x: -x[1]):
        lines.append(f"'{verb}': {c}회 (한계 3) {'⚠️ 초과' if c > 3 else '✓'}")
    cs = counts['연속주어']
    lines.append(f"연속 주어 최대: {cs}문장 (한계 6) {'⚠️ 초과' if cs > 6 else '✓'}")
    for kw, c in sorted(counts.get('등급직업', {}).items(), key=lambda x: -x[1]):
        lines.append(f"'{kw}': {c}회 (한계 2) {'⚠️ 초과' if c > 2 else '✓'}")
    return '\n'.join(lines)


REVIEW_SCHEMA: dict = {
    "type": "object",
    "properties": {
        "판정": {"type": "string", "enum": ["통과", "반려"]},
        "점수": {"type": "integer", "minimum": 0, "maximum": 10},
        "이유": {"type": "string"},
        "수정가이드": {"type": "string"},
    },
    "required": ["판정", "점수", "이유", "수정가이드"],
}


def build_reviewer_prompt(role: str, ctx, draft: str) -> str:
    """검수자별 slim 컨텍스트 — 필요한 정보만 주어 모델 집중도 ↑."""
    if role not in REVIEWER_DEFS:
        raise ValueError(f"알 수 없는 검수자 역할: {role}")
    r = REVIEWER_DEFS[role]

    theme = ctx.theme.strip() if ctx.theme else ""
    chapter_intent = ctx.chapter_outline.overall.strip()

    if role == "direction":
        context_block = (
            f"[작품 전체 플롯]\n{ctx.plot_outline.strip()}\n\n"
            + (f"[작품 테마/약속 — 절대 어기지 말 것]\n{theme}\n\n" if theme else "")
            + f"[현재 회차({ctx.current_chapter_n}화) 의도]\n{chapter_intent}\n\n"
        )
    elif role == "character":
        naming_block = f"[호칭표]\n{ctx.naming_table.strip()}\n\n" if ctx.naming_table else ""
        # 캐릭터 검수자는 theme.md 미포함 — theme 안 자가점검 체크리스트가 모델을
        # '범용 작품 평론가' 모드로 끌고 가서 정의/본문 비교에 집중 못 하게 함.
        context_block = (
            f"[등장인물 정의]\n{ctx.characters.strip()}\n\n"
            + naming_block
        )
    elif role == "quality":
        context_block = (
            "[작품 톤 약속]\n"
            "- 남성향, 시니컬, 약간 유머\n"
            "- 짧은 문장 + 빠른 호흡\n"
            "- 신파 최소화. 감정은 행동/대사로 보여줌\n"
            "- 회차는 클리프행어로 마무리 (한국 웹소설 표준)\n"
            "- 같은 문장/구문 반복 금지\n"
            "- 장면 전환은 자연스럽게 (시간/공간 점프 금지)\n\n"
            f"[현재 회차({ctx.current_chapter_n}화) 의도]\n{chapter_intent}\n\n"
        )
    elif role == "repetition":
        counts = _count_repetition_patterns(draft)
        context_block = (
            f"[사전 카운트 결과 — 정규식 추출 (서술 텍스트만)]\n"
            f"{_format_count_report(counts)}\n\n"
        )
    else:
        context_block = ""

    role_reminder = ""
    if role == "repetition":
        role_reminder = (
            "[최종 리마인더 — 반드시 이 형식만 출력. 다른 텍스트 절대 금지.]\n"
            '출력 예시 (통과): {"판정":"통과","점수":9,"이유":"모든 반복 패턴 한계 이내","수정가이드":""}\n'
            '출력 예시 (반려): {"판정":"반려","점수":3,"이유":"서술 이준 21회(한계15 초과)","수정가이드":"이준 6회 이상을 그는/그가로 교체"}\n'
            '키 이름은 반드시 "판정","점수","이유","수정가이드"를 사용. "결과" 등 다른 키 사용 금지.\n\n'
        )
    elif role == "character":
        role_reminder = (
            "[최종 리마인더 — 본문 읽은 직후 반드시 이 순서로 자문 후 판정]\n"
            "Q1. 본문 첫 단락의 강이준 등급/직업 표기를 따옴표로 인용하라.\n"
            "    예: 본문='F급 짐꾼' / 본문='만년 S급 헌터'.\n"
            "Q2. [등장인물 정의]의 강이준 등급/직업은 'F급 짐꾼'이다.\n"
            "    Q1 인용 ≠ 'F급 짐꾼' 이면 → 즉시 '반려', 점수 ≤ 3.\n"
            "Q3. 본문 첫 단락의 박세린 등급/직업 표기를 따옴표로 인용하라.\n"
            "    [등장인물 정의]의 박세린은 'B급 어쌔신'이다. 다르면 → 즉시 '반려', 점수 ≤ 3.\n"
            "Q4. 호칭 검사 — 다음 두 가지를 모두 본문에서 직접 추출하라:\n"
            "    (가) 서술문에 '\\'이준 씨\\'라 부르며' / '\\'이준 씨\\'라 부르는' / '\\'이준 씨\\'라 불렀다' 등 '이준 씨' 호칭을 명시한 문장이 있는가? 있다면 N=true.\n"
            "    (나) 박세린이 직접 발화한 큰따옴표 대사 (예: \"강이준, 오늘은…\", \"이준 씨, …\")의 첫 호명을 모두 모은다.\n"
            "         · 첫 호명이 '강이준'인 대사 개수 = a (예: \"강이준, …\" 형태).\n"
            "         · 첫 호명이 '이준 씨'인 대사 개수 = b (예: \"이준 씨, …\" 형태).\n"
            "    판정: N=true 이고 b=0 (즉, 서술은 '이준 씨'라 한다고 선언했지만 실제 대사에서 '이준 씨' 호명이 0회) → 즉시 '반려', 점수 ≤ 3.\n"
            "    구체 사례: 본문에 '세린은 그를 \\'이준 씨\\'라 부르는 유일한 동료였다.'가 있고, 박세린 대사가 '강이준, 오늘은 D급 던전이야', '강이준, 출발해', '강이준, 더 빨리' 세 개라면 → N=true, a=3, b=0 → 호칭 모순 반려.\n"
            "Q5. Q1~Q4 모두 통과하면 '통과'. '이유' 필드에 반드시 정의-본문 인용 비교를 적어라.\n"
            "    예 (통과): \"정의='F급 짐꾼' / 본문='F급 짐꾼' 일치, 정의='B급 어쌔신' / 본문='B급 어쌔신' 일치, 호칭 N=∅\".\n"
            "    예 (반려): \"정의='F급 짐꾼' / 본문='S급 헌터' 정반대\".\n"
            "절대 금지 (이유 필드에 쓰면 검수 실패): '서사적 흐름', '권력 획득', '몰입', '완성도', "
            "'4가지 핵심', '카타르시스', '자연스러운', '클리셰', '강력한 기반', '제시된 모든 조건/규칙/요구사항을 충족' 같은 모호한 일반 평어. "
            "오직 정의-본문 인용 비교 결과만 적어라.\n\n"
        )

    return (
        f"[검수자 역할]\n{r['name']}\n\n"
        f"{r['instruction']}\n\n"
        f"{context_block}"
        f"[검수 대상 본문]\n{draft.strip()}\n\n"
        f"{role_reminder}"
        f"[출력 — 다음 JSON 스키마를 정확히 지켜라. 다른 텍스트 절대 금지.]\n"
        f'{{"판정": "통과" 또는 "반려", "점수": 0~10 정수, "이유": "한 문장", '
        f'"수정가이드": "반려 시 가이드, 통과면 빈 문자열"}}'
    )
